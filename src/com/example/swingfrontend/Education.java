// package com.frontend.model;

public class Education {
    private String level;
    private String schoolOrCollegeName;
    private String obtainedScore;
    private String totalScore;
    private String percentage;

    // Getters and Setters
    public String getLevel() { return level; }
    public void setLevel(String level) { this.level = level; }

    public String getSchoolOrCollegeName() { return schoolOrCollegeName; }
    public void setSchoolOrCollegeName(String schoolOrCollegeName) { this.schoolOrCollegeName = schoolOrCollegeName; }

    public String getObtainedScore() { return obtainedScore; }
    public void setObtainedScore(String obtainedScore) { this.obtainedScore = obtainedScore; }

    public String getTotalScore() { return totalScore; }
    public void setTotalScore(String totalScore) { this.totalScore = totalScore; }

    public String getPercentage() { return percentage; }
    public void setPercentage(String percentage) { this.percentage = percentage; }
}
